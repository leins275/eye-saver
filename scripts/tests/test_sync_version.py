"""Tests for scripts/sync_version.py (single version source of truth).

Self-contained by design: no shared conftest. Every test that writes does so
in a throwaway repo built under ``tmp_path`` -- the real checkout is only
ever read, so a failing test can never leave it dirty.
"""

from __future__ import annotations

import importlib.util
import json
import re
import subprocess
import sys
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parents[2]
SCRIPT = REPO_ROOT / "scripts" / "sync_version.py"

_spec = importlib.util.spec_from_file_location("sync_version", SCRIPT)
sync_version = importlib.util.module_from_spec(_spec)
assert _spec.loader is not None
sys.modules["sync_version"] = sync_version  # dataclass introspection needs this
_spec.loader.exec_module(sync_version)


PACKAGE_JSON = '{\n  "name": "eye-saver",\n  "private": true,\n  "version": "0.1.0",\n  "type": "module"\n}\n'
TAURI_CONF = (
    '{\n  "$schema": "https://schema.tauri.app/config/2",\n  "productName": "Eye Saver",\n'
    '  "version": "0.1.0",\n  "identifier": "com.eyesaver.desktop"\n}\n'
)
CARGO_TOML = (
    "[workspace]\n"
    'resolver = "2"\n'
    'members = ["crates/eye-core", "src-tauri"]\n'
    "\n"
    "[workspace.package]\n"
    'version = "0.1.0"\n'
    'edition = "2021"\n'
    "\n"
    "[profile.release]\n"
    "lto = true\n"
)
PACKAGE_LOCK = (
    "{\n"
    '  "name": "eye-saver",\n'
    '  "version": "0.1.0",\n'
    '  "lockfileVersion": 3,\n'
    '  "requires": true,\n'
    '  "packages": {\n'
    '    "": {\n'
    '      "name": "eye-saver",\n'
    '      "version": "0.1.0",\n'
    '      "dependencies": {\n'
    '        "react": "^19.2.0"\n'
    "      }\n"
    "    },\n"
    '    "node_modules/react": {\n'
    '      "version": "19.2.0",\n'
    '      "resolved": "https://registry.npmjs.org/react/-/react-19.2.0.tgz"\n'
    "    }\n"
    "  }\n"
    "}\n"
)
CARGO_LOCK = (
    "# This file is automatically @generated by Cargo.\n"
    "# It is not intended for manual editing.\n"
    "version = 4\n"
    "\n"
    "[[package]]\n"
    'name = "eye-core"\n'
    'version = "0.1.0"\n'
    "dependencies = [\n"
    ' "serde",\n'
    "]\n"
    "\n"
    "[[package]]\n"
    'name = "eye-saver"\n'
    'version = "0.1.0"\n'
    "dependencies = [\n"
    ' "eye-core",\n'
    "]\n"
    "\n"
    "[[package]]\n"
    'name = "eye-saver-extra"\n'
    'version = "0.1.0"\n'
    "\n"
    "[[package]]\n"
    'name = "serde"\n'
    'version = "1.0.219"\n'
    'source = "registry+https://github.com/rust-lang/crates.io-index"\n'
)


def _fake_repo(root: Path, *, with_locks: bool = True) -> Path:
    (root / "src-tauri").mkdir(parents=True)
    (root / "version.txt").write_bytes(b"0.1.0\n")
    (root / "package.json").write_bytes(PACKAGE_JSON.encode())
    (root / "src-tauri" / "tauri.conf.json").write_bytes(TAURI_CONF.encode())
    (root / "Cargo.toml").write_bytes(CARGO_TOML.encode())
    if with_locks:
        (root / "package-lock.json").write_bytes(PACKAGE_LOCK.encode())
        (root / "Cargo.lock").write_bytes(CARGO_LOCK.encode())
    return root


def _snapshot(root: Path) -> dict[str, bytes]:
    return {
        p.relative_to(root).as_posix(): p.read_bytes()
        for p in root.rglob("*")
        if p.is_file()
    }


def _run(*args: str) -> subprocess.CompletedProcess:
    return subprocess.run(
        [sys.executable, str(SCRIPT), *args],
        cwd=REPO_ROOT,
        capture_output=True,
        text=True,
        check=False,
    )


# -- the real checkout, read-only ------------------------------------------


def test_version_file_is_one_semver_line():
    text = (REPO_ROOT / "version.txt").read_text(encoding="utf-8")
    lines = text.splitlines()
    assert len(lines) == 1
    assert re.match(r"^\d+\.\d+\.\d+$", lines[0])


def test_all_present_manifests_match_version_txt():
    version = sync_version.read_version()
    for manifest in sync_version.manifests():
        if manifest.optional and not manifest.path.is_file():
            continue
        assert sync_version.manifest_version(manifest) == version, manifest.path


def test_check_passes_on_the_real_tree():
    result = _run("--check")
    assert result.returncode == 0, result.stdout + result.stderr
    assert "all manifests synced" in result.stdout


def test_print_prints_only_the_version():
    result = _run("--print")
    assert result.returncode == 0
    assert result.stdout.strip() == sync_version.read_version()


def test_set_rejects_a_non_semver():
    result = _run("--set", "1.2")
    assert result.returncode == 2
    assert "not a semver" in result.stderr


def test_the_workspace_version_is_read_from_workspace_package_not_workspace():
    # `[workspace]` and `[workspace.package]` are different sections; the
    # version lives in the latter and only there.
    manifest = next(m for m in sync_version.manifests() if m.kind == "toml")
    assert manifest.section == "workspace.package"


# -- a throwaway repo ------------------------------------------------------


def test_check_reports_nothing_on_a_synced_fake_repo(tmp_path):
    root = _fake_repo(tmp_path)
    assert sync_version.check(root=root) == []


def test_check_names_each_drifting_file(tmp_path):
    root = _fake_repo(tmp_path)
    conf = root / "src-tauri" / "tauri.conf.json"
    conf.write_text(
        conf.read_text().replace('"version": "0.1.0"', '"version": "9.9.9"')
    )
    lock = root / "Cargo.lock"
    lock.write_text(
        sync_version._lock_version_re("eye-core").sub(
            r"\g<1>9.9.9\g<3>", lock.read_text(), count=1
        )
    )

    assert sync_version.check(root=root) == [
        "src-tauri/tauri.conf.json",
        "Cargo.lock (eye-core)",
    ]


def test_check_flags_a_package_lock_whose_two_copies_disagree(tmp_path):
    root = _fake_repo(tmp_path)
    lock = root / "package-lock.json"
    # Only the nested copy drifts: npm would never write this, a hand edit might.
    lock.write_text(
        lock.read_text().replace('      "version": "0.1.0"', '      "version": "0.2.0"')
    )

    assert sync_version.check(root=root) == ["package-lock.json"]


def test_set_writes_every_copy_and_is_idempotent(tmp_path):
    root = _fake_repo(tmp_path)

    sync_version.set_version("1.2.3", root=root)

    assert sync_version.read_version(root) == "1.2.3"
    assert sync_version.check(root=root) == []
    for manifest in sync_version.manifests(root):
        assert sync_version.manifest_version(manifest) == "1.2.3", manifest.path
    for package in sync_version.lock_packages(root):
        assert sync_version.lock_version(package) == "1.2.3", package.name

    first_pass = _snapshot(root)
    sync_version.set_version("1.2.3", root=root)
    assert _snapshot(root) == first_pass, (
        "a repeated --set must be byte-for-byte identical"
    )


def test_set_touches_only_the_version_fields(tmp_path):
    root = _fake_repo(tmp_path)
    before = _snapshot(root)

    sync_version.set_version("1.2.3", root=root)

    after = _snapshot(root)
    # Exactly one version line per copy: version.txt, three manifests, the
    # two package-lock copies, the two Cargo.lock members. The look-alike
    # `eye-saver-extra` entry and the registry crate `serde` stay put.
    expected_changed_lines = {
        "version.txt": 1,
        "package.json": 1,
        "src-tauri/tauri.conf.json": 1,
        "Cargo.toml": 1,
        "package-lock.json": 2,
        "Cargo.lock": 2,
    }
    for name, old in before.items():
        new = after[name]
        changed = [
            (a, b)
            for a, b in zip(old.splitlines(), new.splitlines(), strict=True)
            if a != b
        ]
        assert len(changed) == expected_changed_lines[name], (name, changed)
    assert b'name = "eye-saver-extra"\nversion = "0.1.0"' in after["Cargo.lock"]
    assert b'name = "serde"\nversion = "1.0.219"' in after["Cargo.lock"]
    assert b'"version": "19.2.0"' in after["package-lock.json"]


def test_set_rejects_a_non_semver_before_writing_anything(tmp_path):
    root = _fake_repo(tmp_path)
    before = _snapshot(root)

    with pytest.raises(ValueError):
        sync_version.set_version("1.2", root=root)

    assert _snapshot(root) == before


def test_missing_lockfiles_are_skipped_not_reported(tmp_path):
    # A fresh checkout has no Cargo.lock until the first build; that must
    # neither fail --check nor stop --set from syncing what is there.
    root = _fake_repo(tmp_path, with_locks=False)

    assert sync_version.check(root=root) == []
    assert sync_version.skipped_lockfiles(root) == ["package-lock.json", "Cargo.lock"]

    sync_version.set_version("2.0.0", root=root)

    assert sync_version.check(root=root) == []
    assert not (root / "Cargo.lock").exists()
    assert not (root / "package-lock.json").exists()


def test_cli_notes_a_skipped_lockfile(tmp_path, monkeypatch, capsys):
    root = _fake_repo(tmp_path, with_locks=False)
    monkeypatch.setattr(sync_version, "REPO_ROOT", root)

    assert sync_version.main(["--check"]) == 0

    captured = capsys.readouterr()
    assert "note: Cargo.lock does not exist yet -- skipped" in captured.err
    assert "all manifests synced at 0.1.0" in captured.out


def test_cli_check_fails_naming_the_drifting_file(tmp_path, monkeypatch, capsys):
    root = _fake_repo(tmp_path)
    monkeypatch.setattr(sync_version, "REPO_ROOT", root)
    (root / "package.json").write_text(PACKAGE_JSON.replace("0.1.0", "0.0.9"))

    assert sync_version.main(["--check"]) == 1

    assert "package.json" in capsys.readouterr().err


def test_cli_set_then_check(tmp_path, monkeypatch, capsys):
    root = _fake_repo(tmp_path)
    monkeypatch.setattr(sync_version, "REPO_ROOT", root)

    assert sync_version.main(["--set", "3.4.5"]) == 0
    assert capsys.readouterr().out.strip() == "3.4.5"
    assert sync_version.main(["--check"]) == 0
    assert (
        json.loads((root / "package-lock.json").read_text())["packages"][""]["version"]
        == "3.4.5"
    )


# -- newline preservation --------------------------------------------------


def test_write_json_version_preserves_a_crlf_files_newline_style(tmp_path):
    """A manifest checked out CRLF (`core.autocrlf=true` on Windows) must stay
    CRLF after a version write -- not flip to LF, and not to the platform
    default either."""
    path = tmp_path / "crlf.json"
    path.write_bytes(b'{\r\n  "name": "x",\r\n  "version": "0.0.0"\r\n}\r\n')

    sync_version._write_json_version(path, "1.2.3")

    raw = path.read_bytes()
    assert b'"version": "1.2.3"' in raw
    assert raw.count(b"\r\n") == raw.count(b"\n"), "every line ending must stay CRLF"


def test_write_json_version_preserves_an_lf_files_newline_style(tmp_path):
    path = tmp_path / "lf.json"
    path.write_bytes(b'{\n  "name": "x",\n  "version": "0.0.0"\n}\n')

    sync_version._write_json_version(path, "1.2.3")

    raw = path.read_bytes()
    assert b'"version": "1.2.3"' in raw
    assert b"\r\n" not in raw, "an LF file must never gain CRLF line endings"


def test_write_toml_version_preserves_the_files_existing_newline_style(tmp_path):
    path = tmp_path / "crlf.toml"
    path.write_bytes(
        b'[workspace]\r\nresolver = "2"\r\n\r\n[workspace.package]\r\nversion = "0.0.0"\r\n'
    )

    sync_version._write_toml_version(path, "workspace.package", "1.2.3")

    raw = path.read_bytes()
    assert b'version = "1.2.3"' in raw
    assert raw.count(b"\r\n") == raw.count(b"\n"), "every line ending must stay CRLF"


def test_write_toml_version_inserts_a_missing_field_into_the_right_section(tmp_path):
    path = tmp_path / "Cargo.toml"
    path.write_bytes(
        b'[workspace]\nresolver = "2"\n\n[workspace.package]\nedition = "2021"\n'
    )

    sync_version._write_toml_version(path, "workspace.package", "1.2.3")

    assert path.read_bytes() == (
        b'[workspace]\nresolver = "2"\n\n[workspace.package]\nversion = "1.2.3"\nedition = "2021"\n'
    )


def test_cargo_lock_members_are_rewritten_with_crlf_intact(tmp_path):
    path = tmp_path / "Cargo.lock"
    path.write_bytes(CARGO_LOCK.replace("\n", "\r\n").encode())
    package = sync_version.LockPackage(path, "eye-saver")

    sync_version.set_lock_version(package, "1.2.3")

    raw = path.read_bytes()
    assert b'name = "eye-saver"\r\nversion = "1.2.3"' in raw
    assert b'name = "eye-saver-extra"\r\nversion = "0.1.0"' in raw
    assert raw.count(b"\r\n") == raw.count(b"\n")


def test_npm_lock_write_refuses_a_file_whose_leading_versions_are_not_the_roots(
    tmp_path,
):
    # A lockfile where some dependency's version appears before the root's
    # would be rewritten wrongly by a blind "first two" replacement; the
    # parse-back guard must refuse instead.
    path = tmp_path / "package-lock.json"
    path.write_text(
        json.dumps(
            {
                "name": "x",
                "packages": {
                    "node_modules/a": {"version": "1.0.0"},
                    "": {"name": "x", "version": "0.1.0"},
                },
                "version": "0.1.0",
            },
            indent=2,
        )
    )
    before = path.read_bytes()

    with pytest.raises(ValueError):
        sync_version._write_npm_lock_version(path, "2.0.0")

    assert path.read_bytes() == before
